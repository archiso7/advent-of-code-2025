fn problem_one(input: &str) -> (i64, String) {
    let mut total = 0;
    let lines: Vec<&str> = input.lines().collect();
    let num_rows = lines.len();
    let mut output = String::new();

    for (l, line) in lines.iter().enumerate() {
        if l > 0 {
            output.push('\n');
        }
        let num_cols = line.len();
        for (c, ch) in line.chars().enumerate() {
            if ch == '@' {
                let mut surrounding = 0;
                for di in 0..3i64 {
                    for dj in 0..3i64 {
                        if di == 1 && dj == 1 {
                            continue; // skip the center (self)
                        }
                        let ni = l as i64 + di - 1;
                        let nj = c as i64 + dj - 1;
                        // Check bounds
                        if ni >= 0 && ni < num_rows as i64 && nj >= 0 && nj < num_cols as i64 {
                            if lines[ni as usize].as_bytes()[nj as usize] == b'@' {
                                surrounding += 1;
                            }
                        }
                    }
                }
                if surrounding < 4 {
                    total += 1;
                    output.push('.'); // replace removed @ with .
                } else {
                    output.push('@'); // keep @ with enough neighbors
                }
            } else {
                output.push(ch);
            }
        }
    }
    (total, output)
}

fn problem_two(input: &str) -> i64 {
    let mut total = 0;
    let mut round_total = 1;
    let mut round_input = input.to_string();
    while round_total != 0 {
        (round_total, round_input) = problem_one(&round_input);
        total += round_total;
    }
    total
}

